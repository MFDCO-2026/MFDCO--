begin;

alter table public.countries
  add column if not exists usage_policy_confirmed_at timestamptz,
  add column if not exists published_at timestamptz;

alter table public.country_notifications
  add column if not exists priority text not null default 'normal',
  add column if not exists action_label text not null default '',
  add column if not exists action_url text not null default '',
  add column if not exists related_type text not null default '',
  add column if not exists related_id text not null default '',
  add column if not exists pushed_at timestamptz,
  add column if not exists emailed_at timestamptz;

-- Users may only mark their own notification read; delivery metadata is server-owned.
revoke update on public.country_notifications from authenticated;
grant update(read_at) on public.country_notifications to authenticated;

alter table public.country_notifications drop constraint if exists country_notifications_priority_check;
alter table public.country_notifications add constraint country_notifications_priority_check check(priority in ('normal','important','critical'));

create table if not exists public.country_account_settings (
  user_id uuid primary key references auth.users(id) on delete cascade,
  notification_preferences jsonb not null default '{"push_enabled":false,"email_enabled":false,"level":"important","quiet_enabled":false,"quiet_start":"23:00","quiet_end":"07:00"}'::jsonb,
  default_usage_policy jsonb not null default '{"appearance":"anyone","creditMode":"optional","creditFormat":"","creditExample":"","commercialUse":"allow","commercialNotes":"","settingModification":"unlimited","settingModificationNotes":"","defeatDestruction":"allow","defeatNotes":"","flagUse":"allow","anthemUse":"allow","attributionName":"","requestUrl":"","otherConditions":"","legalNote":""}'::jsonb,
  updated_at timestamptz not null default now()
);
alter table public.country_account_settings enable row level security;
drop policy if exists country_account_settings_own on public.country_account_settings;
create policy country_account_settings_own on public.country_account_settings for all to authenticated using(user_id=auth.uid()) with check(user_id=auth.uid());
grant select,insert,update,delete on public.country_account_settings to authenticated;

create table if not exists public.country_push_subscriptions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  endpoint text not null unique,
  p256dh text not null,
  auth_key text not null,
  device_label text not null default '',
  user_agent text not null default '',
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now()
);
create index if not exists country_push_subscriptions_user_idx on public.country_push_subscriptions(user_id,enabled);
alter table public.country_push_subscriptions enable row level security;
drop policy if exists country_push_subscriptions_own_read on public.country_push_subscriptions;
create policy country_push_subscriptions_own_read on public.country_push_subscriptions for select to authenticated using(user_id=auth.uid());
revoke insert,update,delete on public.country_push_subscriptions from anon,authenticated;
grant select on public.country_push_subscriptions to authenticated;

create table if not exists public.country_notification_delivery_queue (
  id bigint generated by default as identity primary key,
  notification_id bigint not null unique references public.country_notifications(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  push_status text not null default 'skipped' check(push_status in ('pending','processing','sent','failed','skipped')),
  email_status text not null default 'skipped' check(email_status in ('pending','processing','sent','failed','skipped')),
  attempts integer not null default 0,
  next_attempt_at timestamptz not null default now(),
  last_error text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists country_notification_delivery_pending_idx on public.country_notification_delivery_queue(next_attempt_at) where push_status='pending' or email_status='pending';
alter table public.country_notification_delivery_queue enable row level security;
revoke all on public.country_notification_delivery_queue from anon,authenticated;

create or replace function public.mfdco_account_settings_touch()
returns trigger language plpgsql set search_path=public as $$ begin new.updated_at=now();return new;end $$;
drop trigger if exists country_account_settings_touch on public.country_account_settings;
create trigger country_account_settings_touch before update on public.country_account_settings for each row execute function public.mfdco_account_settings_touch();

create or replace function public.mfdco_register_push_subscription(p_subscription jsonb,p_device_label text default '')
returns uuid language plpgsql security definer set search_path=public as $$
declare v_id uuid;v_endpoint text;v_p256dh text;v_auth text;
begin
 if auth.uid() is null then raise exception 'authentication required';end if;
 v_endpoint:=coalesce(p_subscription->>'endpoint','');v_p256dh:=coalesce(p_subscription#>>'{keys,p256dh}','');v_auth:=coalesce(p_subscription#>>'{keys,auth}','');
 if v_endpoint='' or v_p256dh='' or v_auth='' then raise exception 'invalid push subscription';end if;
 insert into public.country_push_subscriptions(user_id,endpoint,p256dh,auth_key,device_label,user_agent,enabled,last_seen_at)
 values(auth.uid(),v_endpoint,v_p256dh,v_auth,coalesce(p_device_label,''),'',true,now())
 on conflict(endpoint) do update set user_id=auth.uid(),p256dh=excluded.p256dh,auth_key=excluded.auth_key,device_label=excluded.device_label,enabled=true,updated_at=now(),last_seen_at=now()
 returning id into v_id;return v_id;
end $$;
revoke all on function public.mfdco_register_push_subscription(jsonb,text) from public;
grant execute on function public.mfdco_register_push_subscription(jsonb,text) to authenticated;

create or replace function public.mfdco_unregister_push_subscription(p_endpoint text)
returns boolean language plpgsql security definer set search_path=public as $$
begin update public.country_push_subscriptions set enabled=false,updated_at=now() where endpoint=p_endpoint and user_id=auth.uid();return found;end $$;
revoke all on function public.mfdco_unregister_push_subscription(text) from public;
grant execute on function public.mfdco_unregister_push_subscription(text) to authenticated;

create or replace function public.mfdco_publish_country(p_country_id text)
returns boolean language plpgsql security definer set search_path=public as $$
declare v_core jsonb;v_usage jsonb;
begin
 if not public.mfdco_country_can_manage(p_country_id) then raise exception 'not allowed';end if;
 select core_data into v_core from public.countries where id=p_country_id and archived_at is null for update;
 if v_core is null then raise exception 'country not found';end if;
 v_usage:=v_core->'usagePolicy';if v_usage is null or jsonb_typeof(v_usage)<>'object' then raise exception 'usage policy is required before publishing';end if;
 update public.countries set is_public=true,core_data=jsonb_set(jsonb_set(core_data,'{isPublic}','true'::jsonb,true),'{public}','true'::jsonb,true),usage_policy_confirmed_at=now(),published_at=coalesce(published_at,now()),updated_at=now() where id=p_country_id;
 return true;
end $$;
revoke all on function public.mfdco_publish_country(text) from public;grant execute on function public.mfdco_publish_country(text) to authenticated;

create or replace function public.mfdco_unpublish_country(p_country_id text)
returns boolean language plpgsql security definer set search_path=public as $$
begin if not public.mfdco_country_can_manage(p_country_id) then raise exception 'not allowed';end if;update public.countries set is_public=false,core_data=jsonb_set(jsonb_set(core_data,'{isPublic}','false'::jsonb,true),'{public}','false'::jsonb,true),updated_at=now() where id=p_country_id;return found;end $$;
revoke all on function public.mfdco_unpublish_country(text) from public;grant execute on function public.mfdco_unpublish_country(text) to authenticated;

create or replace function public.mfdco_apply_default_usage_to_owned_countries()
returns integer language plpgsql security definer set search_path=public as $$
declare v_usage jsonb;v_count integer;
begin
 if auth.uid() is null then raise exception 'authentication required';end if;
 select default_usage_policy into v_usage from public.country_account_settings where user_id=auth.uid();v_usage:=coalesce(v_usage,'{}'::jsonb);
 update public.countries set core_data=jsonb_set(core_data,'{usagePolicy}',v_usage,true),usage_policy_confirmed_at=null,updated_at=now() where owner_id=auth.uid() and archived_at is null;
 get diagnostics v_count=row_count;return v_count;
end $$;
revoke all on function public.mfdco_apply_default_usage_to_owned_countries() from public;grant execute on function public.mfdco_apply_default_usage_to_owned_countries() to authenticated;

create or replace function public.mfdco_bulk_publish_owned_countries(p_apply_default_usage boolean default true)
returns integer language plpgsql security definer set search_path=public as $$
declare v_usage jsonb;v_count integer;
begin
 if auth.uid() is null then raise exception 'authentication required';end if;
 select default_usage_policy into v_usage from public.country_account_settings where user_id=auth.uid();v_usage:=coalesce(v_usage,'{}'::jsonb);
 update public.countries set core_data=(case when p_apply_default_usage then jsonb_set(core_data,'{usagePolicy}',v_usage,true) else core_data end),is_public=true,usage_policy_confirmed_at=now(),published_at=coalesce(published_at,now()),updated_at=now() where owner_id=auth.uid() and archived_at is null;
 update public.countries set core_data=jsonb_set(jsonb_set(core_data,'{isPublic}','true'::jsonb,true),'{public}','true'::jsonb,true) where owner_id=auth.uid() and archived_at is null;
 get diagnostics v_count=row_count;return v_count;
end $$;
revoke all on function public.mfdco_bulk_publish_owned_countries(boolean) from public;grant execute on function public.mfdco_bulk_publish_owned_countries(boolean) to authenticated;

create or replace function public.mfdco_bulk_unpublish_owned_countries()
returns integer language plpgsql security definer set search_path=public as $$
declare v_count integer;
begin update public.countries set is_public=false,core_data=jsonb_set(jsonb_set(core_data,'{isPublic}','false'::jsonb,true),'{public}','false'::jsonb,true),updated_at=now() where owner_id=auth.uid() and archived_at is null;get diagnostics v_count=row_count;return v_count;end $$;
revoke all on function public.mfdco_bulk_unpublish_owned_countries() from public;grant execute on function public.mfdco_bulk_unpublish_owned_countries() to authenticated;

create or replace function public.mfdco_enrich_country_notification()
returns trigger language plpgsql set search_path=public as $$
begin
  if coalesce(new.priority,'normal')='normal' then
    if new.notification_type in (
      'member_invitation','member_invitation_accepted',
      'diplomacy','diplomacy_response',
      'usage_request','usage_request_response',
      'country_media_request','country_media_response'
    ) then new.priority='important'; end if;
  end if;
  if coalesce(new.action_url,'')='' then new.action_url=coalesce(new.link,''); end if;
  if coalesce(new.action_label,'')='' and coalesce(new.action_url,'')<>'' then new.action_label='確認する'; end if;
  return new;
end $$;
drop trigger if exists country_notifications_enrich on public.country_notifications;
create trigger country_notifications_enrich before insert on public.country_notifications for each row execute function public.mfdco_enrich_country_notification();

create or replace function public.mfdco_queue_country_notification_delivery()
returns trigger language plpgsql security definer set search_path=public as $$
declare prefs jsonb;lvl text;push_ok boolean;email_ok boolean;
begin
 select notification_preferences into prefs from public.country_account_settings where user_id=new.user_id;prefs:=coalesce(prefs,'{}'::jsonb);lvl:=coalesce(prefs->>'level','important');
 push_ok:=coalesce((prefs->>'push_enabled')::boolean,false) and (lvl='all' or new.priority in ('important','critical'));
 email_ok:=coalesce((prefs->>'email_enabled')::boolean,false) and (lvl='all' or new.priority in ('important','critical'));
 insert into public.country_notification_delivery_queue(notification_id,user_id,push_status,email_status) values(new.id,new.user_id,case when push_ok then 'pending' else 'skipped' end,case when email_ok then 'pending' else 'skipped' end) on conflict(notification_id) do nothing;return new;
end $$;
drop trigger if exists country_notifications_delivery_queue on public.country_notifications;
create trigger country_notifications_delivery_queue after insert on public.country_notifications for each row execute function public.mfdco_queue_country_notification_delivery();

